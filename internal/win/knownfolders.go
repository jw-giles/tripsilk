package win

import "fmt"

// guid mirrors the Windows GUID layout.
type guid struct {
	d1 uint32
	d2 uint16
	d3 uint16
	d4 [8]byte
}

// String formats a GUID the way Microsoft documents them.
func (g guid) String() string {
	return fmt.Sprintf("{%08X-%04X-%04X-%02X%02X-%02X%02X%02X%02X%02X%02X}", g.d1, g.d2, g.d3,
		g.d4[0], g.d4[1], g.d4[2], g.d4[3], g.d4[4], g.d4[5], g.d4[6], g.d4[7])
}

